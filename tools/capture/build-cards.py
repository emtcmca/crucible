#!/usr/bin/env python3
"""Generate the content cards for the demo video.

ONE GENERATOR, ONE PALETTE. Five separate hand-written HTML files would be five
copies of the same stylesheet, and this repository has a standing finding about
what copies do. The palette below is loop.svg's own, sampled from the file.

SELF-CONTAINED OUTPUT on purpose - the CSS is inlined into each card rather
than linked, because a capture run that depends on a second file resolving over
file:// is a capture run that can fail silently and ship an unstyled frame.

EVERY FIGURE ON THESE CARDS IS QUOTED WITH ITS DENOMINATOR AND ITS SOURCE.
That is not decoration: `docs/contest/DECISION-figures-2026-08-30.md` option 2
makes the denominator and the reader-acceptance count part of the claim, so a
card that showed a bare percentage would be publishing something the ruling
does not permit.

    python tools/capture/build-cards.py
"""
