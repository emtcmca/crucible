def card(name, body, source):
    html = ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\n"
            "<title>CRUCIBLE - %s</title>\n"
            "<!-- Generated by tools/capture/build-cards.py. Do not hand-edit;\n"
            "     rebuild it, or the palette drifts from loop.svg. -->\n"
            "<style>%s</style></head>\n<body>\n%s\n"
            "<div class=\"src\"><b>source:</b> %s</div>\n"
            "</body></html>\n" % (name, CSS, body, source))
    (CARDS / name).write_text(html, encoding="utf-8", newline="")
    print("  wrote cards/%s" % name)


